"""Validate the M2.3 activity JSON against the layout, the schedule and the animation assets. Read-only (writes one text report).

  powershell -File Tools/RunHeadless.ps1 -Script Tools/ValidateActivities.py -Log <abs log>

Checks: schema; every interaction point is a NavDest:Yes marker of the layout; the facing prop exists and is in front of the marker;
the arrival tolerance covers the distance the navigation actually stops at (about 95 cm for Move To radius 60); the marker is not
close to an opening; every referenced animation exists, is an AnimSequence on SK_Mannequin (the NPC skeleton); which scheduled
NPCs/periods use each point. Report: Docs/Layout/S01_LW_F1_activities_report.txt.
"""
import math
import os

import unreal

import cw_activity as ca
import cw_layout
import cw_schedule as cs

P = unreal.Paths.project_dir()
data = ca.load()
layout = ca.load_layout()
sched = cs.load()
ex = cw_layout.expand(layout)
types = layout["marker_types"]
markers = {m["id"]: m for m in layout["markers"] + ex["markers"]}
for b in layout["boxes"]:  # cafeteria seats are generated by the builder: Seat_<Table_n>_<1..6> (same rule as ValidateSchedule.py)
    if b.get("seats"):
        cx, cy = (b["x0"] + b["x1"]) / 2.0, (b["y0"] + b["y1"]) / 2.0
        n = 0
        for side in (-1, 1):
            for dx in (-100, 0, 100):
                n += 1
                sid = "Seat_%s_%d" % (b["id"].replace("Prop_Caf_", ""), n)
                markers[sid] = {"id": sid, "type": "CafeteriaSeat", "x": cx + dx, "y": cy + side * 95, "z": 0}
openings = [(o["id"], (o["coord"], o["center"]) if o["axis"] == "v" else (o["center"], o["coord"])) for o in layout["openings"] + ex["openings"]
            if o.get("z0", 0) == 0 and o.get("kind") != "secured"]
errs, out = [], []


def rep(m=""):
    out.append(m)
    unreal.log("[ACTCHK] " + m)


rep("== Schema ==")
ca.validate_schema(data, layout, errs)
rep("  schema errors: %d" % len(errs))

rep("")
rep("== Interaction points ==")
for pt in data["interaction_points"]:
    mid = pt["marker_id"]
    m = markers.get(mid)
    if m is None:
        errs.append("%s: marker does not exist in the layout" % mid)
        continue
    if not types.get(m["type"], {}).get("nav", False):
        errs.append("%s: marker type %s is not a navigation destination" % (mid, m["type"]))
    mode, yaw, target = ca.resolve_facing(pt, layout)
    dist_target = math.hypot(target[0] - m["x"], target[1] - m["y"]) if mode == "point" else None
    bearing = math.degrees(math.atan2(target[1] - m["y"], target[0] - m["x"])) if mode == "point" else yaw
    od = min((math.hypot(m["x"] - ox, m["y"] - oy), oid) for oid, (ox, oy) in openings)
    if od[0] < 250:
        errs.append("%s: only %.0f cm from opening %s (< 250)" % (mid, od[0], od[1]))
    if dist_target is not None and dist_target < 50:
        errs.append("%s: facing target is only %.0f cm away" % (mid, dist_target))
    # The plan task asks Move To for radius = clamp(tolerance - capsule 34 - 20, 10, 60); Move To stops about radius + capsule 34 from the marker
    # (94-99 cm measured at the TV with radius 60), so the tolerance must cover that stop distance plus a small margin.
    move_radius = min(60.0, max(10.0, pt["arrival_tolerance_cm"] - 34.0 - 20.0))
    if pt["arrival_tolerance_cm"] < move_radius + 34.0 + 15.0:
        errs.append("%s: tolerance %.0f cm is below the ~%.0f cm at which Move To (radius %.0f + capsule 34) stops, plus 15 cm margin" % (mid, pt["arrival_tolerance_cm"], move_radius + 34.0, move_radius))
    fa = pt.get("final_approach") or {}
    if fa.get("enabled", False):
        fad = ca.FINAL_APPROACH_DEFAULTS
        maxd = fa.get("max_distance_cm", fad["max_distance_cm"])
        # Move To leaves the NPC about radius + capsule 34 cm from the marker (measured 40-47 cm at radius 10); the final walk must be allowed to cover that plus a margin.
        if maxd < move_radius + 34.0 + 15.0:
            errs.append("%s: final approach maximum distance %.0f cm is below the ~%.0f cm Move To leaves, plus 15 cm margin" % (mid, maxd, move_radius + 34.0))
        if maxd > 80.0:
            errs.append("%s: final approach maximum distance %.0f cm exceeds the approved 80 cm" % (mid, maxd))
        rep("             final approach: accept %.1f cm, tolerance %.1f cm, max %.0f cm, timeout %.1f s (walk starts where Move To stops, ~%.0f cm out)" % (
            fa.get("accept_cm", fad["accept_cm"]), fa.get("tolerance_cm", fad["tolerance_cm"]), maxd, fa.get("timeout_seconds", fad["timeout_seconds"]), move_radius + 34.0))
    users = []
    for nid, a in sched["assignments"].items():
        for pid, e in a["schedule"].items():
            if mid in e["stops"]:
                users.append("%s/%s" % (nid, pid))
    rep("  %-10s -> %-9s marker (%d, %d) facing %s %.1f deg%s ; nearest opening %s %.0f cm ; tolerance %.0f cm ; capacity %d" % (
        mid, pt["activity"], m["x"], m["y"], mode, bearing, (" at distance %.0f cm" % dist_target) if dist_target is not None else "", od[1], od[0], pt["arrival_tolerance_cm"], pt["capacity"]))
    rep("             scheduled use: %s" % (", ".join(users) if users else "NONE (no NPC is scheduled there)"))
    if not users:
        errs.append("%s: no NPC is scheduled to this interaction point" % mid)

rep("")
rep("== Animations ==")
ar = unreal.AssetRegistryHelpers.get_asset_registry()
lengths = {}
for a in data["activities"]:
    for key in ("enter_animation", "loop_animation", "exit_animation"):
        path = a.get(key)
        if not path:
            rep("  %-10s %-15s (none - falls back to the normal idle pose)" % (a["id"], key))
            continue
        asset = unreal.load_asset(path)
        if asset is None or not isinstance(asset, unreal.AnimSequence):
            errs.append("%s.%s: %s is not an existing AnimSequence" % (a["id"], key, path))
            continue
        skel = asset.get_editor_property("skeleton")
        ok = skel is not None and skel.get_name() == "SK_Mannequin"
        rep("  %-10s %-15s %s (%.2f s, skeleton %s)%s" % (a["id"], key, path, asset.get_play_length(), skel.get_name() if skel else None, "" if ok else "  INCOMPATIBLE"))
        if not ok:
            errs.append("%s.%s: skeleton is not SK_Mannequin" % (a["id"], key))
        lengths[(a["id"], key)] = asset.get_play_length() / a.get("play_rate", 1.0)
    # Timing: a cross-fade must fit inside the clip it fades out of (here half of it, so the clip still shows its own pose in the middle).
    bi, bo = a.get("blend_in_seconds", 0.0), a.get("blend_out_seconds", 0.0)
    inherit = lambda k, d: a[k] if a.get(k, -1.0) >= 0 else d
    if (a["id"], "enter_animation") in lengths:
        cross = inherit("loop_blend_in_seconds", bi)
        if cross > lengths[(a["id"], "enter_animation")] / 2.0:
            errs.append("%s: loop cross-fade %.2f s is longer than half the enter animation (%.2f s)" % (a["id"], cross, lengths[(a["id"], "enter_animation")]))
    if (a["id"], "exit_animation") in lengths:
        cross = inherit("exit_blend_in_seconds", bi)
        if cross + inherit("exit_blend_out_seconds", bo) > lengths[(a["id"], "exit_animation")]:
            errs.append("%s: exit blend in + blend out (%.2f s) exceed the exit animation (%.2f s)" % (a["id"], cross + inherit("exit_blend_out_seconds", bo), lengths[(a["id"], "exit_animation")]))
    rep("  %-10s timing: enter blend-in %.2f, enter->loop cross-fade %.2f, loop->exit cross-fade %.2f, exit blend-out %.2f, release grace %s, commit enter %s" % (
        a["id"], inherit("enter_blend_in_seconds", bi), inherit("loop_blend_in_seconds", bi), inherit("exit_blend_in_seconds", bi), inherit("exit_blend_out_seconds", bo),
        ("%.2f s" % a["release_grace_seconds"]) if a.get("release_grace_seconds", -1) >= 0 else "component default", a.get("commit_enter", False)))

rep("")
rep("RESULT: %s" % ("PASS (0 problems)" if not errs else "FAIL (%d problem(s))" % len(errs)))
for e in errs:
    rep("  - " + e)
with open(os.path.join(P, "Docs", "Layout", "S01_LW_F1_activities_report.txt"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
unreal.SystemLibrary.quit_editor()
