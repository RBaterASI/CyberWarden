"""M2.3 Stage C0 step 5b: the three Mixamo clips are authored around different origins (stand-to-sit leaves the pelvis ~46 cm behind
where sitting-idle starts, sit-to-stand ends ~46 cm in front of standing). This rigidly shifts the pelvis track of SEAT_SittingIdle
and SEAT_SitToStand (XY only) so every hand-off lines up, using the pose difference between consecutive clips. Idempotent: a clip
that already lines up (< 1 cm) is left alone. Only touches the retargeted SEAT_* assets (regenerated by C0_RunRetarget.py).
Report: Saved/C0_AlignSeated.txt
"""
import unreal

SEAT = "/Game/CyberWarden/Anims/Seated/"
out = []


def p(m):
    out.append(str(m))
    unreal.log("[C0] " + str(m))


def pelvis_at(a, t):
    return unreal.AnimationLibrary.get_bone_pose_for_time(a, "pelvis", t, False).translation


def shift_pelvis(a, dx, dy):
    model = a.get_editor_property("data_model_interface") if hasattr(a, "data_model_interface") else a.data_model
    keys = model.get_number_of_keys()
    p("  %s: %d keys (%d frames)" % (a.get_name(), keys, unreal.AnimationLibrary.get_num_frames(a)))
    pos, rot, scl = [], [], []
    for i in range(keys):
        tr = unreal.AnimationLibrary.get_bone_pose_for_time(a, "pelvis", i / 30.0, False)
        v = tr.translation
        pos.append(unreal.Vector(v.x + dx, v.y + dy, v.z))
        rot.append(tr.rotation)
        scl.append(tr.scale3d)
    c = a.controller
    c.open_bracket("C0 align seated clip origin")
    c.set_bone_track_keys("pelvis", pos, rot, scl)
    c.close_bracket()
    unreal.EditorAssetLibrary.save_loaded_asset(a)
    return keys


s2s = unreal.load_asset(SEAT + "SEAT_StandToSit")
idle = unreal.load_asset(SEAT + "SEAT_SittingIdle")
s2u = unreal.load_asset(SEAT + "SEAT_SitToStand")

e = pelvis_at(s2s, s2s.get_play_length())
b = pelvis_at(idle, 0.0)
dx, dy = e.x - b.x, e.y - b.y
p("StandToSit end pelvis (%.1f, %.1f) vs SittingIdle start (%.1f, %.1f): shift idle by (%.1f, %.1f)" % (e.x, e.y, b.x, b.y, dx, dy))
if (dx * dx + dy * dy) ** 0.5 > 1.0:
    p("  shifted %s keys" % shift_pelvis(idle, dx, dy))
else:
    p("  already aligned")

e = pelvis_at(idle, idle.get_play_length())
b = pelvis_at(s2u, 0.0)
dx, dy = e.x - b.x, e.y - b.y
p("SittingIdle end pelvis (%.1f, %.1f) vs SitToStand start (%.1f, %.1f): shift stand by (%.1f, %.1f)" % (e.x, e.y, b.x, b.y, dx, dy))
if (dx * dx + dy * dy) ** 0.5 > 1.0:
    p("  shifted %s keys" % shift_pelvis(s2u, dx, dy))
else:
    p("  already aligned")

end = pelvis_at(s2u, s2u.get_play_length())
start = pelvis_at(s2s, 0.0)
p("standing start pelvis (%.1f, %.1f) -> after SitToStand pelvis (%.1f, %.1f): round-trip offset %.1f cm" % (start.x, start.y, end.x, end.y, ((end.x - start.x) ** 2 + (end.y - start.y) ** 2) ** 0.5))

with open(unreal.Paths.project_saved_dir() + "C0_AlignSeated.txt", "w") as fh:
    fh.write("\n".join(out))
unreal.SystemLibrary.quit_editor()
